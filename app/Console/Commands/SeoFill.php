    public function handle(): int
    {
        $force = (bool) $this->option('force');

        $rows = [];
        $filled = 0;
        $skipped = 0;

        foreach (['packages' => Package::class, 'products' => Product::class, 'templates' => Template::class] as $label => $model) {
            foreach ($model::query()->orderBy('id')->get() as $record) {
                $copy = $this->copyFor($record);

                if (! $force && trim((string) $record->meta_title) !== '' && trim((string) $record->meta_description) !== '') {
                    $skipped++;

                    continue;
                }

                $record->forceFill([
                    'meta_title' => $copy['title'],
                    'meta_description' => $copy['description'],
                ])->save();

                $filled++;
                $rows[] = [$label, (string) $record->name, (string) $record->slug, $copy['title']];
            }
        }

        $this->info("پرشدن فیلدهای سئو تمام شد — {$filled} رکورد به‌روزرسانی شد، {$skipped} رکورد قبلاً پر بود (از --force برای بازنویسی استفاده کنید).");

        if ($rows !== []) {
            $this->table(['نوع', 'نام', 'نامک', 'عنوان متای جدید'], $rows);
        }

        return self::SUCCESS;
    }

    /**
     * متن سئوی رکورد: اول متن دقیق بر اساس نامک؛ در غیر این صورت متن باکیفیت خودکار.
     *
     * @return array{title: string, description: string}
     */
    private function copyFor(Package|Product|Template $record): array
    {
        $slug = (string) $record->slug;

        if (isset(self::SEO_COPY[$slug])) {
            return self::SEO_COPY[$slug];
        }

        // تطبیق بدون حساسیت به بزرگی/کوچکی حروف
        foreach (self::SEO_COPY as $key => $copy) {
            if (mb_strtolower($key) === mb_strtolower($slug)) {
                return $copy;
            }
        }

        return $this->generatedCopy($record);
    }

    /** تولید متن سئوی باکیفیت برای رکوردهای فهرست‌نشده */
    private function generatedCopy(Package|Product|Template $record): array
    {
        $name = trim((string) $record->name);

        if ($record instanceof Package) {
            $title = "خرید پکیج {$name} شاپ‌پرو | ماژول حرفه‌ای فروشگاه‌ساز";
            $base = trim(strip_tags((string) $record->short_description));
            $description = $base !== ''
                ? "پکیج {$name} برای فروشگاه‌ساز شاپ‌پرو: ".Str::limit($base, 105).' خرید با نصب فوری، آپدیت تضمینی و پشتیبانی فارسی از آپدیت‌سنتر.'
                : "پکیج {$name} برای فروشگاه‌ساز شاپ‌پرو با نصب فوری، آپدیت تضمینی و پشتیبانی فارسی؛ خرید مستقیم از آپدیت‌سنتر.";
        } elseif ($record instanceof Product) {
            $title = "خرید {$name} | پروژهٔ آمادهٔ کامل تحت وب";
            $base = trim(strip_tags((string) $record->short_description));
            $description = $base !== ''
                ? "{$name}: ".Str::limit($base, 110).' دانلود فوری پس از پرداخت آنلاین، آپدیت تضمینی و پشتیبانی فارسی از آپدیت‌سنتر.'
                : "پروژهٔ آمادهٔ {$name} با کد کامل، نصب ساده و مستندات فارسی؛ دانلود فوری پس از پرداخت آنلاین از آپدیت‌سنتر.";
        } else {
            $title = "خرید قالب آمادهٔ {$name} | طراحی واکنش‌گرا و سئو شده";
            $base = trim(strip_tags((string) $record->short_description));
            $description = $base !== ''
                ? "قالب آمادهٔ {$name}: ".Str::limit($base, 110).' خرید با نصب فوری، آپدیت تضمینی و پشتیبانی فارسی از آپدیت‌سنتر.'
                : "قالب آمادهٔ {$name} با طراحی واکنش‌گرا، سئوی قوی و نصب ساده؛ دانلود فوری پس از پرداخت آنلاین از آپدیت‌سنتر.";
        }

        return [
            'title' => Str::limit($title, 200, ''),
            'description' => Str::limit($description, 500, ''),
        ];
    }
